//	========================== 1. ВСТАНОВЛЕННЯ Git ==========================
//	git --version
//	(якщо команда не знайдена - встановити з www.git-scm.com)

//	========================== 2. НАЛАШТУВАННЯ Git ==========================
//	git config --global user.name "Your Name"
//	git config --global user.email "your@email.com"
//
//	Переглянути поточні налаштування (без зміни):
//	git config --global user.name
//	git config --global user.email

//	========================== 3. СТВОРЕННЯ РЕПОЗИТОРІЮ (разом із GitHub) ==========================
//	1)  Спочатку створити ПОРОЖНІЙ репозиторій на самому GitHub (сайт github.com →
//	    кнопка New repository → ввести назву → Create repository). Не додавати
//	    README/.gitignore при створенні - інакше виникне конфлікт на кроці push.
//	2)  У терміналі, перебуваючи ВСЕРЕДИНІ папки проєкту:
//	    git init
//	3)  Прив'язати локальний репозиторій до щойно створеного на GitHub:
//	    git remote add origin https://github.com/username/repo.git
//	4)  Перший коміт і відправка (докладніше про add/commit - у розділах 4-5 нижче):
//	    git add .
//	    git commit -m "First commit"
//	    git push -u origin main
//	Після цього "git push" без прапорців працюватиме сам (розділ 6).

//	========================== 4. НАКОПИЧУВАЛЬНИЙ БУФЕР (staging area) ==========================
//	git status                 - показує, що зараз у робочому каталозі, а що вже в буфері
//	git diff                   - показує зміни у файлах, які ще НЕ в буфері
//	git diff --staged          - те саме, але для файлів, які вже в буфері
//	git add ім'я_файлу         - додати ОДИН файл у буфер (підготувати до комміту)
//	git add .                  - додати УСІ змінені файли одразу
//	git restore --staged ім'я_файлу   - прибрати файл з буфера назад (нічого не видаляє, лише "розкомітовує")

//	========================== 5. ЗАПИС КОМІТУ (git commit) ==========================
//	git commit -m "Додав функцію ім'яФункції"       - комітиться лише те, що вже в буфері (пройшло через git add)
//	git commit -a -m "Додав функцію ім'яФункції"    - ВСІ змінені відстежувані файли одразу, без попереднього git add
//	(новий файл, якого Git ще не знає, і тут треба спершу git add)
//	Коміт зберігає зміни ЛОКАЛЬНО. На GitHub вони потрапляють тільки після git push.

//	========================== 6. git fetch / pull / push ==========================
//	git fetch                  - дізнатись про нові коміти на GitHub, нічого не змінюючи у файлах
//	git pull                   - fetch + merge у поточну гілку
//	git pull --rebase          - fetch + rebase замість merge (чистіша історія, див. розділ 13)
//	git push                   - відправити локальні коміти на GitHub
//	git status                 - у першому рядку видно "ahead/behind" відносно сервера
//	Якщо push відхилено (rejected) - спочатку git pull, вирішити конфлікти, потім знову git push.

//	========================== 7. ГІЛКИ (branches) ==========================
//	git branch                 - показати список усіх гілок (поточна позначена *)
//	git branch feature-x       - створити нову гілку (НЕ перемикає на неї)
//	git checkout feature-x     - перемкнутись на вже створену гілку (сучасна команда: git switch feature-x)
//	git checkout -b feature-x  - створити гілку і ОДРАЗУ перемкнутись на неї (2 в 1; сучасна: git switch -c feature-x)

//	========================== 8. ЗЛИТТЯ ГІЛОК (git merge) ==========================
//	git switch main            - перемкнутись на гілку, В ЯКУ вливаємо
//	git pull                   - оновити main
//	git merge feature-x        - влити feature-x у поточну гілку (main)
//	git log --oneline --graph --all     - подивитись історію з гілками
//	Конфлікт: git status покаже "both modified". Відкрити файл, залишити потрібне, видалити маркери
//	<<<<<<<, =======, >>>>>>>, потім:
//	git add файл
//	git commit                 - Git запропонує готове повідомлення "Merge branch 'feature-x'", зберегти його
//	git merge --abort          - скасувати злиття, що почалось, і повернутись до стану до merge

//	========================== 9. КЛОНУВАННЯ (git clone) ==========================
//	git clone https://github.com/user/repo.git
//	Виконується НЕ всередині вже існуючої папки проєкту, а там, де має з'явитись
//	нова папка - Git сам створить підпапку з назвою репозиторію.

//	========================== 10. GITIGNORE (.gitignore) ==========================
//	Звичайний текстовий файл - окремої git-команди для його створення немає:
//	echo x64/ > .gitignore
//	echo *.obj >> .gitignore
//	(> створює файл і пише перший рядок, >> дописує далі). Після створення
//	комітиться звичайним способом: git add .gitignore + git commit.

//	========================== 11. ПЕРЕГЛЯД ІСТОРІЇ І CHECKOUT ==========================
//	git log --oneline          - короткий список комітів (хеш + повідомлення)
//	git switch main            - перемкнутись на гілку (git checkout main робить те саме)
//	git switch -               - повернутись на попередню гілку
//	git checkout a1b2c3d       - подивитись старий коміт за хешем (detached HEAD: не на гілці, коміти тут легко загубити)
//	git switch -c rescue       - якщо в detached HEAD зробили щось цінне: зберегти це у новій гілці
//	git switch main            - повернутись із detached HEAD
//	git restore файл           - скасувати НЕзакомічені зміни у файлі (зміни зникають безповоротно!)
//	git restore --source=a1b2c3d файл   - повернути файл у тому вигляді, що був у коміті a1b2c3d

//	========================== 12. ВІДКАТ ЗМІН: reset і revert ==========================
//	git reset --soft HEAD~1    - скасувати останній коміт, зміни ЛИШАЮТЬСЯ в буфері (staged)
//	git reset HEAD~1           - (--mixed, за замовчуванням) скасувати коміт, зміни лишаються у файлах, але НЕ в буфері
//	git reset --hard HEAD~1    - скасувати коміт І ВСІ зміни. НЕБЕЗПЕЧНО: незакомічена робота зникає
//	git reset --hard a1b2c3d   - відкотитись до конкретного коміту
//	HEAD~1 означає "на один коміт назад від поточного", HEAD~3 - на три.
//	git revert a1b2c3d         - створити новий коміт, що скасовує коміт a1b2c3d (історія не переписується)
//	git reflog                 - журнал усіх переміщень HEAD: рятівник, якщо помилково зробили reset --hard
//	                             (знайти хеш втраченого стану і git reset --hard хеш)
//	Правило: reset - тільки для ще не відправлених (не push) комітів. Для відправлених - git revert.

//	========================== 13. git rebase ==========================
//	git switch feature
//	git rebase main            - перенести коміти feature на верхівку main
//	Конфлікт: виправити файл, потім
//	git add файл
//	git rebase --continue      - перейти до наступного коміту
//	git rebase --abort         - скасувати rebase повністю
//	git push --force-with-lease     - після rebase опублікованої гілки (звичайний push буде відхилено).
//	                             Безпечніший за --force: не затре чужі коміти, якщо на сервері щось з'явилось.
//	git rebase -i HEAD~3       - інтерактивний rebase: об'єднати (squash), перейменувати, переставити останні 3 коміти
//	Золоте правило: не робіть rebase комітів, які вже є в колег. Тільки для вашої власної, ще не спільної гілки.

//	========================== 14. PULL REQUEST (повний цикл через CLI) ==========================
//	git switch -c feature-x               - нова гілка
//	(правки, git add ., git commit -m "Додав ...")
//	git push -u origin feature-x          - відправити гілку на GitHub (-u лише перший раз)
//	Далі на github.com: Compare & pull request → Create pull request → ревю → Merge pull request → Delete branch.
//	(Якщо встановлено GitHub CLI: gh pr create - те саме з терміналу, але це окремий інструмент.)
//	Після злиття на GitHub - прибрати за собою локально:
//	git switch main
//	git pull                              - отримати результат злиття
//	git branch -d feature-x               - видалити локальну гілку
//	git fetch --prune                     - прибрати локальні посилання на гілки, видалені на GitHub